import { choose, createIssue, newProject, openProject, peek, row, search, sidebar } from "../helpers/page";
import { expect, signIn, test } from "../helpers/test";

test("My issues follows assignment, completion and project archival from another member", async ({ browser }) => {
  const ada = await signIn(browser, "ada");
  const bob = await signIn(browser, "bob");
  const project = await newProject(ada, "Assigned");
  const title = `Assigned ${crypto.randomUUID()}`;
  await createIssue(ada, title);
  await sidebar(bob).getByRole("link", { name: "My issues", exact: true }).click();
  await search(bob, title);
  await expect(row(bob, title)).toHaveCount(0);
  await choose(ada, row(ada, title).getByLabel("Assignee: Unassigned"), "Bob");
  await expect(row(bob, title)).toBeVisible();
  await choose(ada, row(ada, title).getByLabel("State: Backlog"), "Done");
  await expect(row(bob, title)).toHaveCount(0);
  await choose(ada, row(ada, title).getByLabel("State: Done"), "Todo");
  await expect(row(bob, title)).toBeVisible();
  await sidebar(ada).getByRole("link", { name: "Settings", exact: true }).click();
  await ada.getByRole("button", { name: "Archive project" }).click();
  await expect(row(bob, title)).toHaveCount(0);
  await sidebar(ada).getByRole("link", { name: "Projects", exact: true }).click();
  await ada.getByRole("listitem", { name: project.name }).getByRole("button", { name: "Restore" }).click();
  await expect(row(bob, title)).toBeVisible();
});

