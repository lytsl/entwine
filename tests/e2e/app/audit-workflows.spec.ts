test("System theme follows OS changes and deliberate same-user tabs share the choice", async ({ browser }) => {
  const page = await signIn(browser, "ada");
  await page.emulateMedia({ colorScheme: "light" });
  await page.keyboard.press("ControlOrMeta+k");
  const palette = page.getByRole("dialog", { name: "Command palette" });
  await palette.getByRole("combobox").fill("system");
  await palette.getByRole("option", { name: "System theme", exact: true }).click();
  await expect(page.locator("html")).not.toHaveClass(/dark/);
  await page.emulateMedia({ colorScheme: "dark" });
  await expect(page.locator("html")).toHaveClass(/dark/);
  const second = await page.context().newPage();
  await second.goto(page.url());
  await expect(second.getByTestId("sync-status")).toHaveText("Live");
  await second.keyboard.press("ControlOrMeta+k");
  const otherPalette = second.getByRole("dialog", { name: "Command palette" });
  await otherPalette.getByRole("combobox").fill("light");
  await otherPalette.getByRole("option", { name: "Light theme", exact: true }).click();
  await expect(page.locator("html")).not.toHaveClass(/dark/);
  await expect(second.locator("html")).not.toHaveClass(/dark/);
});

test("renaming and deleting a used label updates another member's issue", async ({ browser }) => {
  const ada = await signIn(browser, "ada");
  const bob = await signIn(browser, "bob");
  const name = `Label ${crypto.randomUUID()}`;
  await sidebar(ada).getByRole("link", { name: "Labels", exact: true }).click();
  await ada.getByRole("button", { name: "New label", exact: true }).click();
  await ada.getByLabel("New label", { exact: true }).fill(name);
  await ada.getByRole("button", { name: "Create", exact: true }).click();
  await expect(ada.getByRole("listitem", { name, exact: true })).toBeVisible();
  const project = await newProject(ada, "Tagged");
  const title = `Tagged ${crypto.randomUUID()}`;
  await createIssue(ada, title);
  const panel = await peek(ada, title);
  await panel.getByLabel("Labels", { exact: true }).click();
  await ada.getByRole("option", { name, exact: true }).click();
  await ada.keyboard.press("Escape");
  await panel.getByRole("button", { name: "Close preview", exact: true }).click();
  await openProject(bob, project.name);
  await expect(row(bob, title).getByLabel(`Labels: ${name}`, { exact: true })).toBeVisible();
  await sidebar(ada).getByRole("link", { name: "Labels", exact: true }).click();
  await ada.getByRole("button", { name: `Edit ${name}`, exact: true }).click();
  const renamed = `${name} edited`;
  await ada.getByLabel("Label name", { exact: true }).fill(renamed);
  await ada.getByRole("button", { name: "Save", exact: true }).click();
  await expect(row(bob, title).getByLabel(`Labels: ${renamed}`, { exact: true })).toBeVisible();
  await ada.getByRole("button", { name: `Delete ${renamed}`, exact: true }).click();
  await expect(row(bob, title).getByLabel(/^Labels:/)).toHaveCount(0);
  await expect((await peek(bob, title)).getByLabel("Labels", { exact: true })).toBeVisible();
  await expect(ada.getByRole("listitem", { name: renamed, exact: true })).toHaveCount(0);
});

test("project details update live and a duplicate identifier is refused in the form", async ({ browser }) => {
  const ada = await signIn(browser, "ada");
  const bob = await signIn(browser, "bob");
  const project = await newProject(ada, "General");
  const title = `General ${crypto.randomUUID()}`;
  await createIssue(ada, title);
  await openProject(bob, project.name);
  await expect(row(bob, title)).toContainText(`${project.identifier}-1`);
  await sidebar(ada).getByRole("link", { name: "Settings", exact: true }).click();
  await ada.getByLabel("Identifier", { exact: true }).fill("WEB");
  await ada.getByRole("button", { name: "Save changes", exact: true }).click();
  await expect(ada.getByText("Identifier WEB is taken", { exact: true })).toBeVisible();
  const identifier = `Z${crypto.randomUUID().slice(0, 4).toUpperCase()}`;
  const name = `${project.name} edited`;
  await ada.getByLabel("Identifier", { exact: true }).fill(identifier);
  await ada.getByLabel("Name", { exact: true }).fill(name);
  await ada.getByLabel("Description", { exact: true }).fill("Updated project description");
  await ada.getByRole("button", { name: "Save changes", exact: true }).click();
  await expect(sidebar(bob).getByRole("link", { name, exact: true })).toBeVisible();
  await expect(row(bob, title)).toContainText(`${identifier}-1`);
  await ada.reload();
  await expect(ada.getByLabel("Description", { exact: true })).toHaveValue("Updated project description");
  await expect(ada.getByLabel("Identifier", { exact: true })).toHaveValue(identifier);
});

test("switching workspaces keeps each workspace's projects and issues separate", async ({ browser }) => {
  const page = await signIn(browser, "ada");
  const name = `Separate ${crypto.randomUUID().slice(0, 8)}`;
  await sidebar(page).getByRole("button", { name: "Acme", exact: true }).click();
  await page.getByRole("menuitem", { name: "Create workspace", exact: true }).click();
  await page.getByLabel("Name", { exact: true }).fill(name);
  await page.getByRole("button", { name: "Create workspace", exact: true }).click();
  await expect(page.getByTestId("sync-status")).toHaveText("Live");
  const project = await newProject(page, "Separate");
  const title = `Separate ${crypto.randomUUID()}`;
  await createIssue(page, title);
  await expect(row(page, title)).toBeVisible();
  await sidebar(page).getByRole("button", { name, exact: true }).click();
  await page.getByRole("menuitem", { name: "A Acme", exact: true }).click();
  await expect(page.getByTestId("sync-status")).toHaveText("Live");
  await expect(sidebar(page).getByRole("link", { name: "Website", exact: true })).toBeVisible();
  await expect(sidebar(page).getByRole("link", { name: project.name, exact: true })).toHaveCount(0);
  await sidebar(page).getByRole("button", { name: "Acme", exact: true }).click();
  await page.getByRole("menuitem", { name: `S ${name}`, exact: true }).click();
  await expect(page.getByTestId("sync-status")).toHaveText("Live");
  await expect(sidebar(page).getByRole("link", { name: "Website", exact: true })).toHaveCount(0);
  await openProject(page, project.name);
  await expect(row(page, title)).toBeVisible();
});
